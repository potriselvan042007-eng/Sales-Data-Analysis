import pandas as pd
import matplotlib.pyplot as plt

# Convert order_date safely
df["order_date"] = pd.to_datetime(
    df["order_date"],
    format="mixed",
    dayfirst=True,
    errors="coerce"
)

# Check converted dates
print(df["order_date"].head())
print("Invalid dates:", df["order_date"].isna().sum())

# Create monthly sales
monthly_sales = (
    df.groupby(df["order_date"].dt.to_period("M"))["sales_amount"]
    .sum()
    .reset_index()
)

# Convert month to text for display
monthly_sales["order_date"] = monthly_sales["order_date"].astype(str)

# Plot
plt.figure(figsize=(10, 4))

plt.plot(
    monthly_sales["order_date"],
    monthly_sales["sales_amount"],
    marker="o"
)

plt.title("Monthly Sales Trend")
plt.xlabel("Month")
plt.ylabel("Total Sales")
plt.xticks(rotation=45)

plt.tight_layout()
plt.show()

# Total Quantity
